"""Export content_blocks to PowerPoint PPTX file.
Pattern borrowed from OpenMAIC pptxgenjs export."""

import logging
from pathlib import Path

logger = logging.getLogger(__name__)


from pptx.util import Pt as _Pt


def _add_content_slide(prs, title: str, content: str, font_name: str | None = None,
                       font_size: int | None = None, bold: bool = False) -> None:
    slide_layout = prs.slide_layouts[1]
    slide = prs.slides.add_slide(slide_layout)
    slide.shapes.title.text = title
    if slide.placeholders and len(slide.placeholders) > 1:
        tf = slide.placeholders[1].text_frame
        tf.text = content
        for paragraph in tf.paragraphs:
            if font_name:
                paragraph.font.name = font_name
            if font_size:
                paragraph.font.size = _Pt(font_size)
            if bold:
                paragraph.font.bold = True


def export_to_pptx(content_blocks: list[dict], output_path: str, title: str = "AI学习资源") -> str:
    """Convert content_blocks to a .pptx file. Returns output_path."""
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
    except ImportError:
        logger.error("python-pptx not installed. Run: pip install python-pptx")
        raise

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    slide.shapes.title.text = title
    if slide.placeholders and len(slide.placeholders) > 1:
        slide.placeholders[1].text = "Generated by AI Learning System"

    for block in content_blocks:
        block_type = block.get("type", "text")
        block_title = block.get("heading", "")
        block_content = block.get("content", "")

        if block_type == "section":
            _add_content_slide(prs, block_title or block_content[:100], block_content)

        elif block_type == "code":
            _add_content_slide(prs, block_title or "代码示例", block_content,
                               font_name="Consolas", font_size=14)

        elif block_type == "callout":
            _add_content_slide(prs, block_title or "重点提示", block_content,
                               font_size=18, bold=True)

        else:
            _add_content_slide(prs, block_title or "内容", block_content)

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    prs.save(output_path)
    logger.info(f"PPTX exported to {output_path}, {len(content_blocks)} blocks")
    return output_path
